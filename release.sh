#!/bin/bash
# Release The Tribal Plugin. See RELEASE.md.
#   1. Checks the version numbers agree
#   2. Builds dist/svn/ (the plugin files exactly as they ship)
#   3. Asks: create dist/zip/TTT_WordPress_Plugin.<version>.zip?
#   4. Asks: release to WordPress.org SVN? (yes / dry run / no)
#      sync dist/svn into trunk -> review -> commit trunk -> tag trunk@REV as tags/<version>
# Asks before every write to SVN. SVN prompts for the password itself; never pass it here.
#
# Env: SVN_WC=<path>      local trunk working copy (default ~/svn/the-tech-tribe-trunk)
#      WPORG_USER=<name>  WordPress.org username (asked if not set)
set -euo pipefail

cd "$(dirname "$0")"
PLUGIN_DIR=$(pwd)

PLUGIN_ROOT="the-tech-tribe"
MAIN_FILE="the-tribal-plugin.php"
DIST_SVN="$PLUGIN_DIR/dist/svn"
DIST_ZIP="$PLUGIN_DIR/dist/zip"
REPO="https://plugins.svn.wordpress.org/the-tech-tribe"
SVN_WC="${SVN_WC:-$HOME/svn/the-tech-tribe-trunk}"

# Allowlist: ONLY these ship (vendor/ is generated by Composer). Anything new
# (dotfiles, tests, tooling, notes) stays out unless it is added here on purpose.
SHIP=(
  admin app assets helpers includes languages public
  index.php the-tribal-plugin.php uninstall.php README.txt LICENSE.txt
)

# Every svn call goes through this wrapper:
# - http-max-connections=1: the WSL/Linux svn client opens several parallel connections
#   by default, which trips WordPress.org's rate limit (HTTP 429)
# - never store the password unencrypted
SVN_OPTS=(
  --config-option servers:global:http-max-connections=1
  --config-option servers:global:store-plaintext-passwords=no
)
svn() { command svn "${SVN_OPTS[@]}" "$@"; }

die()  { echo "❌ $*" >&2; exit 1; }
info() { echo "▶ $*"; }
ask()  { local a; read -r -p "$1 [y/N] " a; [[ "$a" =~ ^[Yy]$ ]]; }
# The SVN working copy is only a mirror of trunk: resetting it never loses real work
reset_wc() {
  svn revert -R -q .
  svn status --no-ignore | awk '/^[?I]/ {print $2}' | xargs -r rm -rf
}
plugin_version() { grep -i "^[[:space:]]*\* Version:" "$1" | head -n 1 | sed -E 's/.*Version:[[:space:]]*([0-9.]+).*/\1/'; }

# ---------------------------------------------------------------
# 1. Version consistency: header Version, constant, readme Stable tag, changelog
# ---------------------------------------------------------------
for cmd in composer zip rsync svn git; do command -v "$cmd" >/dev/null || die "$cmd is not installed."; done

VERSION=$(plugin_version "$MAIN_FILE")
CONSTANT=$(grep -E "define\( *'THE_TRIBAL_PLUGIN_VERSION'" "$MAIN_FILE" | sed -E "s/.*'([0-9.]+)'.*/\1/")
STABLE=$(grep -i "^Stable tag:" README.txt | sed -E 's/^Stable tag:[[:space:]]*([0-9.]+).*/\1/')

[ -n "$VERSION" ] || die "Could not read Version from $MAIN_FILE."
[ "$CONSTANT" = "$VERSION" ] && [ "$STABLE" = "$VERSION" ] \
  || die "Version mismatch — header: $VERSION, THE_TRIBAL_PLUGIN_VERSION: ${CONSTANT:-missing}, Stable tag: ${STABLE:-missing}"
grep -qE "^= *$VERSION( |=)" README.txt || die "No '= $VERSION' entry in the README.txt changelog."

info "Version $VERSION"

# ---------------------------------------------------------------
# 2. Build dist/svn (Composer runs inside it; the dev vendor/ is never touched)
# ---------------------------------------------------------------
info "Building dist/svn/..."
rm -rf "$PLUGIN_DIR/dist"
mkdir -p "$DIST_SVN"
for item in "${SHIP[@]}"; do
  [ -e "$item" ] || die "Expected '$item' is missing."
  cp -R "$item" "$DIST_SVN/"
done
cp composer.json composer.lock "$DIST_SVN/"
composer install --working-dir="$DIST_SVN" --no-dev --optimize-autoloader --no-interaction --quiet
rm -f "$DIST_SVN/composer.json" "$DIST_SVN/composer.lock"
# Drop OS/editor junk that can hide inside shipped folders
find "$DIST_SVN" -mindepth 1 \( -name '.*' -o -name '*~' -o -name '__MACOSX' \) -prune -exec rm -rf {} +
echo "✅ dist/svn/: $(find "$DIST_SVN" -type f | wc -l) files"

# ---------------------------------------------------------------
# 3. Zip (optional)
# ---------------------------------------------------------------
if ask "Create the zip?"; then
  ZIP_FILE="$DIST_ZIP/TTT_WordPress_Plugin.${VERSION}.zip"
  mkdir -p "$DIST_ZIP"
  TMP=$(mktemp -d)
  trap 'rm -rf "$TMP"' EXIT
  cp -R "$DIST_SVN" "$TMP/$PLUGIN_ROOT"
  (cd "$TMP" && zip -qrX "$ZIP_FILE" "$PLUGIN_ROOT")
  echo "✅ dist/zip/$(basename "$ZIP_FILE") ($(du -sh "$ZIP_FILE" | cut -f1))"
fi

# ---------------------------------------------------------------
# 4. SVN release (optional)
# ---------------------------------------------------------------
read -r -p "Release $VERSION to WordPress.org SVN? [y = release / d = dry run / N = no] " MODE
case "$MODE" in
  [Yy]) DRY_RUN=no ;;
  [Dd]) DRY_RUN=yes ;;
  *) info "Done. No SVN release."; exit 0 ;;
esac

# Release only committed, pushed code
if [ "$DRY_RUN" = "no" ]; then
  [ -z "$(git status --porcelain)" ] || die "Git has uncommitted changes. Commit them, then rerun."
  git fetch -q 2>/dev/null || true
  if UPSTREAM=$(git rev-parse -q --verify '@{u}' 2>/dev/null) && ! git merge-base --is-ancestor HEAD "$UPSTREAM"; then
    ask "HEAD is not pushed to $(git rev-parse --abbrev-ref '@{u}'). Release anyway?" || die "Stopped. Push first."
  fi
fi

# The tag must not exist yet
if svn ls "$REPO/tags/$VERSION" >/dev/null 2>&1; then
  die "tags/$VERSION already exists on WordPress.org. Published tags are never overwritten — bump the version."
fi

# Working copy: check out once, then update; must be clean
if [ ! -d "$SVN_WC/.svn" ]; then
  ask "No SVN working copy at $SVN_WC. Check out trunk there now?" || die "Stopped."
  mkdir -p "$(dirname "$SVN_WC")"
  svn checkout -q "$REPO/trunk" "$SVN_WC" \
    || die "Checkout failed (a 429 means rate limiting): wait a minute, run 'svn cleanup' in $SVN_WC, then rerun."
fi
cd "$SVN_WC"
[ "$(svn info --show-item url)" = "$REPO/trunk" ] || die "$SVN_WC is not a checkout of $REPO/trunk."

info "Updating SVN working copy..."
svn update -q || die "svn update failed (a 429 means rate limiting): wait a minute, run 'svn cleanup' in $SVN_WC, then rerun."
if [ -n "$(svn status)" ]; then
  svn status
  echo "$SVN_WC has leftover local changes (e.g. from an interrupted run). It is only a mirror of trunk."
  ask "Discard them and reset it to trunk?" || die "Stopped. Nothing was sent to WordPress.org."
  reset_wc
  [ -z "$(svn status)" ] || die "Reset failed. Delete $SVN_WC and rerun (it will check out again)."
fi

TRUNK_VERSION=$(plugin_version "$MAIN_FILE" || true)
if [ -n "$TRUNK_VERSION" ] && [ "$TRUNK_VERSION" != "$VERSION" ] \
   && [ "$(printf '%s\n%s\n' "$TRUNK_VERSION" "$VERSION" | sort -V | tail -n 1)" != "$VERSION" ]; then
  die "Trunk is at $TRUNK_VERSION, which is newer than $VERSION."
fi

# Sync dist/svn into trunk and stage adds/deletes
info "Syncing dist/svn/ into trunk..."
rsync -a --delete --exclude=.svn "$DIST_SVN/" ./
svn add --force --quiet .
svn status | awk '/^!/ {print $2}' | xargs -r svn rm --quiet

if [ -z "$(svn status)" ]; then
  # Trunk already holds this build (e.g. an earlier run committed but didn't tag)
  REV=$(svn info --show-item last-changed-revision)
  info "Trunk already matches dist/svn (last changed in r$REV). Nothing to commit."
else
  echo
  svn status
  echo
  if ask "Show the full diff?"; then svn diff | less -R; fi
  if [ "$DRY_RUN" = "yes" ]; then
    reset_wc
    info "Dry run: stopped before commit. SVN working copy reverted."
    exit 0
  fi

  # Commit trunk
  WPORG_USER="${WPORG_USER:-}"
  [ -n "$WPORG_USER" ] || read -r -p "WordPress.org username: " WPORG_USER
  read -r -p "Type the version ($VERSION) to commit trunk: " CONFIRM
  [ "$CONFIRM" = "$VERSION" ] || die "Stopped. Nothing committed (local changes are still in $SVN_WC)."

  info "Committing trunk — SVN will ask for the password: use the SVN password from Keeper."
  OUT=$(mktemp)
  svn commit --username "$WPORG_USER" -m "Release $VERSION" | tee "$OUT"
  REV=$(sed -n 's/^Committed revision \([0-9]*\)\.$/\1/p' "$OUT")
  rm -f "$OUT"
  [ -n "$REV" ] || die "Could not read the committed revision. Check $REPO/trunk, then rerun (it will skip to tagging)."
fi

[ "$DRY_RUN" = "yes" ] && { info "Dry run: stopped before tagging."; exit 0; }

# Tag exactly the committed revision
TAGGED_VERSION=$(svn cat "$REPO/trunk/$MAIN_FILE@$REV" | grep -i "^[[:space:]]*\* Version:" | head -n 1 | sed -E 's/.*Version:[[:space:]]*([0-9.]+).*/\1/')
[ "$TAGGED_VERSION" = "$VERSION" ] || die "trunk@$REV is version $TAGGED_VERSION, not $VERSION. Not tagging."

ask "Create tags/$VERSION from trunk@$REV? This publishes the release." || die "Stopped. Trunk is committed (r$REV); rerun to tag."
WPORG_USER="${WPORG_USER:-}"
[ -n "$WPORG_USER" ] || read -r -p "WordPress.org username: " WPORG_USER
svn copy --username "$WPORG_USER" "$REPO/trunk@$REV" "$REPO/tags/$VERSION" -m "Tagging version $VERSION"

# Verify
if [ -z "$(svn diff --summarize "$REPO/trunk@$REV" "$REPO/tags/$VERSION")" ]; then
  echo "✅ tags/$VERSION matches trunk@$REV"
else
  echo "⚠️  tags/$VERSION differs from trunk@$REV — investigate before announcing."
fi

cat <<EOF

Released $VERSION to SVN (trunk r$REV, tags/$VERSION).
If release confirmation is on, approve it from the email or the plugin's Advanced tab.
After a few minutes, follow the "Verify" steps in RELEASE.md.
EOF
